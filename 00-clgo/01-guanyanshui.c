/*
    挂盐水
Description
挂盐水的时候,如果滴起来有规律,先是滴一滴,停一下;然后滴二滴,停一下;再滴三滴,停一下.现在有个何题:这瓶盐水一共有VUL毫升,每
一滴是D毫升,每一滴的速度是一秒(假设最后一酒不到D毫升,则花费的时间也,一秒),停下的时间也是一秒这瓶水什么时候能挂完呢?
Input
输入数据居包含多个测试实例,每个实例占一行,由VUL和nD组成,其中0<D<VUL<5000.(输入EOF说明结束)
Output
对于每组测试数据,请输出挂完盐水需要的时间,每个实例的输出占一行。
*/

#include <stdio.h>

int main(void)
{
    int VUL, D;

    while (scanf("%d%d", &VUL, &D) == 2)
    {
        /* 需要的总滴数（最后一滴不足 D 毫升也算一滴） */
        int need = (VUL + D - 1) / D;

        /* 找到最小轮数 k，使得 1 + 2 + ... + k >= need */
        int k = 1;
        while ((long long)k * (k + 1) / 2 < need)
            ++k;

        /*
         * 第 k 轮滴完时结束，之前共有 k-1 次停顿，
         * 每滴耗时 1 秒，故总时间 = 滴数 + 停顿次数 = need + (k - 1)
         */
        printf("%d\n", need + k - 1);
    }

    return 0;
}