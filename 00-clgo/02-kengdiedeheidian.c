/*
今天小明去了一个风景如画的地方散心，但是自己带的饮料喝完了，小明口渴难耐，见不远处有家小商店，于是跑去买饮料。

小明：“我要买饮料！”
店主：“我们这里有三种饮料，矿泉水1.5元一瓶，可乐2元一瓶，橙汁3.5元一瓶。”
小明：“好的，给我一瓶矿泉水。”
说完他掏出一张N元的大钞递给店主。

店主：“我忘了提醒你了，我们这里没有找客人钱的习惯的，多的钱我们都当小费收了的，嘿嘿。”
小明：“……”

小明环顾四周，就这一家商店，况且实在太渴了，就决定在这买了。不过小明想，与其把钱当小费送给他，还不如自己多买一点饮料，反正早晚都要喝，但是要尽量少让他赚小费。

现在小明希望你能帮他计算一下，最少他要给店主多少小费。
*/

#include <stdlib.h>
#include <stdio.h>
#include <string.h>

int main()
{

    int t, n;
    scanf("%d", &t);
    for (int i = 0; i < t; ++i)
    {
        scanf("%d", &n);
        if (n < 150)
        {
            printf("%d\n", n - 150);
        }
        else if (n < 200)
        {
            printf("%d\n", n - 200);
        }
        else
        {
            printf("%d\n", n % 50);
        }
    }
    return 0;
}